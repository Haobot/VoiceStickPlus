    /// 二分查找（表按码点升序；查不到返回 nil，调用方按不同音保守拒绝）。
    public static func find(_ cp: UInt32) -> PinyinEntry? {
        var low = 0
        var high = table.count
        while low < high {
            let mid = (low + high) / 2
            if table[mid].cp < cp {
                low = mid + 1
            } else {
                high = mid
            }
        }
        guard low < table.count, table[low].cp == cp else { return nil }
        return table[low]
    }
